// Commit-message rules: the Conventional Commits 1.0.0 structure first, then
// the policy this plugin adds on top. The two layers are reported together but
// stay distinguishable: `unknown-type` or `missing-space` are structural,
// `description-not-chinese` or `forbidden-trailer` are plugin policy.
//
// Everything here is pure: no git, no filesystem, no environment. The CLI
// wrapper in `skills/shipping-github/scripts/` and the `git_commit_check` tool
// both call these functions, so a project and the bundled checker cannot drift.

export const COMMIT_TYPES = [
  'feat',
  'fix',
  'build',
  'chore',
  'ci',
  'docs',
  'style',
  'refactor',
  'perf',
  'test',
  'revert',
] as const

export type CommitType = (typeof COMMIT_TYPES)[number]

/** Trailers that are valid Conventional Commits footers but forbidden here. */
export const IDENTITY_TRAILERS = ['co-authored-by', 'signed-off-by'] as const

export const MAX_DESCRIPTION_LENGTH = 50
export const MAX_MESSAGE_LENGTH = 20_000

export interface CommitIssue {
  code: string
  message: string
  line?: number
}

export interface CommitFooter {
  token: string
  value: string
  line: number
}

export interface ParsedCommit {
  type: string
  scope?: string
  breaking: boolean
  description: string
  body: string
  footers: CommitFooter[]
}

export interface CommitCheckOptions {
  /** Replace the default type set (tests and projects with a fixed dialect). */
  allowedTypes?: readonly string[]
  /** Additional project-declared types; appended to the default set. */
  extraTypes?: readonly string[]
  /** Require a Chinese description and enforce the 50-character style. */
  requireChinese?: boolean
  /** Trailers the project explicitly requires, e.g. DCO `signed-off-by`. */
  allowedTrailers?: readonly string[]
}

export interface CommitCheckResult {
  valid: boolean
  parsed?: ParsedCommit
  issues: CommitIssue[]
}

const HEADER_RE = /^([A-Za-z][A-Za-z0-9]*)(?:\(([^()\r\n]+)\))?(!)?: (.+)$/
const FOOTER_RE = /^(BREAKING CHANGE|[A-Za-z][A-Za-z0-9-]*)(?:: | #)(.*)$/
const IDENTITY_LINE_RE = /^(co-authored-by|signed-off-by)\s*:/i
const BREAKING_LIKE_RE = /^breaking[ -]change\s*(?:: | #)/i
const HAN_RE = /\p{Script=Han}/u

const CURSOR_MARKERS: ReadonlyArray<{ code: string; pattern: RegExp; label: string }> = [
  { code: 'forbidden-cursor-agent', pattern: /cursoragent/i, label: 'cursoragent' },
  { code: 'forbidden-made-with-cursor', pattern: /made with cursor/i, label: 'Made with Cursor' },
  {
    code: 'forbidden-generated-by-cursor',
    pattern: /generated by cursor/i,
    label: 'Generated by Cursor',
  },
  {
    code: 'forbidden-cursor-coauthor',
    pattern: /^co-authored-by:\s*.*\bcursor\b/im,
    label: 'Cursor in Co-authored-by',
  },
]

function normalizeAllowedTrailers(values: readonly string[] | undefined): Set<string> {
  return new Set(
    (values ?? []).map((value) => value.trim().toLowerCase()).filter((value) => value !== ''),
  )
}

function resolveTypes(options: CommitCheckOptions): Set<string> {
  const base = options.allowedTypes ?? COMMIT_TYPES
  const all = [...base, ...(options.extraTypes ?? [])]
  return new Set(
    all.map((value) => value.trim().toLowerCase()).filter((value) => value !== ''),
  )
}

function splitFooterSection(lines: string[], offset: number): {
  bodyLines: string[]
  footers: CommitFooter[]
} {
  let cursor = lines.length
  // Trailing blank lines are not part of the body or the footer section.
  while (cursor > 0 && (lines[cursor - 1] ?? '').trim() === '') cursor -= 1
  if (cursor === 0) return { bodyLines: [], footers: [] }

  let start = cursor
  while (start > 0 && (lines[start - 1] ?? '').trim() !== '') start -= 1
  const paragraph = lines.slice(start, cursor)
  if (paragraph.length === 0 || !FOOTER_RE.test(paragraph[0] ?? '')) {
    return { bodyLines: lines.slice(0, cursor), footers: [] }
  }

  const footers: CommitFooter[] = []
  for (let index = 0; index < paragraph.length; index += 1) {
    const line = paragraph[index] ?? ''
    const match = FOOTER_RE.exec(line)
    if (match) {
      footers.push({ token: match[1] ?? '', value: match[2] ?? '', line: offset + start + index + 1 })
      continue
    }
    const current = footers[footers.length - 1]
    if (current) current.value = `${current.value}\n${line}`
  }
  return { bodyLines: lines.slice(0, start), footers }
}

/**
 * Parse one commit message against the official structure and the plugin
 * policy. The parser never throws; every rejection is an issue with a stable
 * `code` so callers can distinguish structure from policy.
 */
export function parseCommitMessage(
  message: string,
  options: CommitCheckOptions = {},
): CommitCheckResult {
  const issues: CommitIssue[] = []
  const normalized = message.replace(/\r\n/g, '\n').replace(/\r/g, '\n')

  if (normalized.trim() === '') {
    return { valid: false, issues: [{ code: 'empty-message', message: '提交信息为空。' }] }
  }
  if (normalized.length > MAX_MESSAGE_LENGTH) {
    issues.push({
      code: 'message-too-long',
      message: `提交信息超过 ${MAX_MESSAGE_LENGTH} 个字符。`,
    })
  }

  const lines = normalized.split('\n')
  const header = lines[0] ?? ''
  const headerMatch = HEADER_RE.exec(header)
  if (!headerMatch) {
    issues.push({
      code: 'invalid-header',
      message:
        '标题必须是 `<type>(scope)!: <description>`：冒号是英文半角且后跟一个空格，`!` 紧贴冒号。',
      line: 1,
    })
    return { valid: false, issues }
  }

  const type = headerMatch[1] ?? ''
  const scope = headerMatch[2]
  const breakingBang = headerMatch[3] === '!'
  const description = (headerMatch[4] ?? '').trim()

  const types = resolveTypes(options)
  if (!types.has(type.toLowerCase())) {
    issues.push({
      code: 'unknown-type',
      message: `类型 \`${type}\` 不在允许集合中：${[...types].join(', ')}。`,
      line: 1,
    })
  }
  if (description === '') {
    issues.push({ code: 'empty-description', message: '描述不能为空。', line: 1 })
  }
  if (scope !== undefined && scope.trim() === '') {
    issues.push({ code: 'empty-scope', message: '范围括号不能为空。', line: 1 })
  }

  if (options.requireChinese === true && scope !== undefined && scope.trim() !== '') {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(scope)) {
      issues.push({
        code: 'invalid-scope',
        message: '扩展模式要求 scope 为小写 kebab-case（例如 `api`、`cli-output`）。',
        line: 1,
      })
    }
  }

  const rest = lines.slice(1)
  if (rest.length > 0 && (rest[0] ?? '').trim() !== '') {
    issues.push({
      code: 'missing-body-blank-line',
      message: '正文必须在标题后空一行再开始。',
      line: 2,
    })
  }

  const { bodyLines, footers } = splitFooterSection(rest, 1)
  const body = bodyLines.join('\n').replace(/^\n+|\n+$/g, '')

  let breakingFooter = false
  for (const footer of footers) {
    if (footer.token === 'BREAKING CHANGE' || footer.token === 'BREAKING-CHANGE') {
      breakingFooter = true
    }
    if (footer.value.trim() === '') {
      issues.push({
        code: 'empty-footer',
        message: `脚注 \`${footer.token}\` 没有内容。`,
        line: footer.line,
      })
    }
  }

  // `BREAKING CHANGE` is the one token the spec requires in uppercase. Catch
  // lowercase or mixed-case variants that would otherwise read as body text.
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index] ?? ''
    if (!BREAKING_LIKE_RE.test(line)) continue
    if (/^BREAKING[ -]CHANGE(?:: | #)/.test(line)) continue
    const lower = line.toLowerCase()
    if (lower.startsWith('breaking change') || lower.startsWith('breaking-change')) {
      issues.push({
        code: 'breaking-change-case',
        message: '`BREAKING CHANGE` / `BREAKING-CHANGE` 必须全大写。',
        line: index + 1,
      })
    }
  }

  const allowedTrailers = normalizeAllowedTrailers(options.allowedTrailers)
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index] ?? ''
    const match = IDENTITY_LINE_RE.exec(line)
    if (!match) continue
    const token = (match[1] ?? '').toLowerCase()
    if (allowedTrailers.has(token)) continue
    issues.push({
      code: 'forbidden-trailer',
      message: `禁止 \`${match[1]}\`；只有项目明文要求的脚注才能通过 allowed_trailers 放行。`,
      line: index + 1,
    })
  }

  for (const marker of CURSOR_MARKERS) {
    const index = lines.findIndex((line) => marker.pattern.test(line))
    if (index === -1) continue
    issues.push({
      code: marker.code,
      message: `提交信息包含禁用标记 \`${marker.label}\`。`,
      line: index + 1,
    })
  }

  if (options.requireChinese === true && description !== '') {
    if (!HAN_RE.test(description)) {
      issues.push({
        code: 'description-not-chinese',
        message: '描述必须至少包含一个汉字；技术专名可以保留英文。',
        line: 1,
      })
    }
    const length = Array.from(description).length
    if (length > MAX_DESCRIPTION_LENGTH) {
      issues.push({
        code: 'description-too-long',
        message: `描述最长 ${MAX_DESCRIPTION_LENGTH} 个字符，当前 ${length} 个。`,
        line: 1,
      })
    }
    if (/[.。]$/.test(description)) {
      issues.push({
        code: 'description-trailing-period',
        message: '描述行末不加句号。',
        line: 1,
      })
    }
  }

  const parsed: ParsedCommit = {
    type,
    breaking: breakingBang || breakingFooter,
    description,
    body,
    footers,
  }
  if (scope !== undefined) parsed.scope = scope
  return { valid: issues.length === 0, parsed, issues }
}

/** Type-checked entry point used by the tool and the CLI wrapper. */
export function checkCommitMessage(
  message: string,
  options: CommitCheckOptions = {},
): CommitCheckResult {
  if (typeof message !== 'string') {
    return {
      valid: false,
      issues: [{ code: 'invalid-message-type', message: '提交信息必须是字符串。' }],
    }
  }
  return parseCommitMessage(message, options)
}

/** Whether a message contains a breaking marker, regardless of other errors. */
export function isBreakingChange(message: string): boolean {
  const header = message.replace(/\r\n/g, '\n').split('\n')[0] ?? ''
  if (/^[A-Za-z][A-Za-z0-9]*(?:\([^()\r\n]+\))?!: /.test(header)) return true
  return /^BREAKING[ -]CHANGE(?:: | #)/m.test(message)
}
