import assert from 'node:assert/strict'
import test from 'node:test'

import {
  COMMIT_TYPES,
  checkCommitMessage,
  isBreakingChange,
  parseCommitMessage,
} from '../lib/commit-rules.js'

const strict = { requireChinese: false }

function codes(message, options = strict) {
  return checkCommitMessage(message, options).issues.map((issue) => issue.code)
}

test('accepts the official examples', () => {
  const samples = [
    'docs: correct spelling of CHANGELOG',
    'feat(api)!: remove the old endpoint',
    'feat: allow config\n\nBREAKING CHANGE: config keys renamed',
    'feat: allow config\n\nBREAKING-CHANGE: config keys renamed',
    'fix: crash on empty input\n\nRefs: #123',
    'Feat: add mixed-case type',
    'feat: add a body\n\nThis explains the change.\n\nReviewed-by: Alice',
  ]
  for (const message of samples) {
    assert.equal(checkCommitMessage(message, strict).valid, true, message)
  }
})

test('accepts a minimal header with no body and no footer', () => {
  const result = parseCommitMessage('chore: bump dev dependency', strict)
  assert.equal(result.valid, true)
  assert.equal(result.parsed.body, '')
  assert.deepEqual(result.parsed.footers, [])
})

test('rejects malformed headers', () => {
  assert.ok(codes('feat：add thing').includes('invalid-header'))
  assert.ok(codes('feat!(api): add thing').includes('invalid-header'))
  assert.ok(codes('feat:add thing').includes('invalid-header'))
  assert.ok(codes('feat(api):add thing').includes('invalid-header'))
  assert.ok(codes('feat:').includes('invalid-header'))
})

test('rejects unknown types unless extra types are enabled', () => {
  assert.ok(codes('wip: temporary').includes('unknown-type'))
  assert.equal(checkCommitMessage('wip: temporary', { ...strict, extraTypes: ['wip'] }).valid, true)
})

test('splits a body only after exactly one blank line', () => {
  assert.ok(codes('feat: add thing\nbody without blank line').includes('missing-body-blank-line'))
  assert.equal(checkCommitMessage('feat: add thing\n\nbody', strict).valid, true)
})

test('parses footers and breaking markers', () => {
  const result = parseCommitMessage(
    'feat(api)!: remove old endpoint\n\nBody text.\n\nBREAKING CHANGE: callers must migrate\nRefs: #42',
    strict,
  )
  assert.equal(result.valid, true)
  assert.equal(result.parsed.breaking, true)
  assert.deepEqual(
    result.parsed.footers.map((footer) => footer.token),
    ['BREAKING CHANGE', 'Refs'],
  )
  assert.equal(isBreakingChange('feat: x\n\nBREAKING-CHANGE: y'), true)
  assert.equal(isBreakingChange('feat: x'), false)
})

test('rejects lowercase breaking-change tokens', () => {
  assert.ok(codes('feat: x\n\nBREAKING CHANGE: y'.toLowerCase()).includes('breaking-change-case'))
  assert.ok(codes('feat: x\n\nBreaking-Change: y').includes('breaking-change-case'))
})

test('identity trailers are rejected by default and can be allow-listed', () => {
  assert.ok(codes('feat: x\n\nSigned-off-by: Alice').includes('forbidden-trailer'))
  assert.equal(
    checkCommitMessage('feat: x\n\nSigned-off-by: Alice', {
      ...strict,
      allowedTrailers: ['Signed-off-by'],
    }).valid,
    true,
  )
})

test('rejects Cursor attribution even without a generic trailer', () => {
  assert.ok(codes('feat: x\n\nCo-authored-by: Cursor <cursor@example.com>').includes('forbidden-cursor-coauthor'))
  assert.ok(codes('feat: x\n\nGenerated by Cursor').includes('forbidden-generated-by-cursor'))
})

test('Chinese extension can be enabled and reports description rules', () => {
  const zh = { requireChinese: true }
  assert.equal(checkCommitMessage('feat: 添加配置项', zh).valid, true)
  assert.ok(codes('feat: add config', zh).includes('description-not-chinese'))
  assert.ok(codes(`feat: ${'字'.repeat(51)}`, zh).includes('description-too-long'))
  assert.ok(codes('feat: 添加配置项。', zh).includes('description-trailing-period'))
  assert.equal(checkCommitMessage('feat(cli-output): 添加配置项', zh).valid, true)
  assert.ok(codes('feat(CLI): 添加配置项', zh).includes('invalid-scope'))
  assert.equal(checkCommitMessage('feat(CLI): add config', strict).valid, true)
})

test('exports the complete default type list', () => {
  assert.deepEqual(COMMIT_TYPES, [
    'feat',
    'fix',
    'build',
    'chore',
    'ci',
    'docs',
    'style',
    'refactor',
    'perf',
    'test',
    'revert',
  ])
})
